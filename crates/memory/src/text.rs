/// Weight of a normalized lexical (BM25) score in the hybrid blend.
pub const LEXICAL_WEIGHT: f32 = 0.6;
/// Weight of cosine similarity in the hybrid blend.
pub const VECTOR_WEIGHT: f32 = 0.4;

/// Split text into lowercase alphanumeric terms, dropping stop words.
pub fn tokenize(text: &str) -> Vec<String> {
    let mut tokens = Vec::new();
    let mut current = String::new();
    for ch in text.chars() {
        if ch.is_alphanumeric() {
            for lower in ch.to_lowercase() {
                current.push(lower);
            }
        } else if !current.is_empty() {
            push_token(&mut tokens, &current);
            current.clear();
        }
    }
    if !current.is_empty() {
        push_token(&mut tokens, &current);
    }
    tokens
}

fn push_token(tokens: &mut Vec<String>, token: &str) {
    if token.chars().count() < 2 || STOP_WORDS.binary_search(&token).is_ok() {
        return;
    }
    tokens.push(token.to_string());
}

/// Build an FTS5 MATCH expression from user text.
///
/// Each term is quoted so punctuation and FTS operators in a pasted query
/// cannot turn into syntax errors. Terms are joined with `OR` rather than the
/// implicit `AND`: a long question usually contains a word the stored fact does
/// not, and BM25 plus vector reranking can rank a partial lexical match above
/// silence. Every term is generated by [`tokenize`], so it is alphanumeric.
pub fn fts_match_query(query: &str) -> Option<String> {
    let mut seen = std::collections::HashSet::new();
    let mut terms = Vec::new();
    for token in tokenize(query) {
        if seen.insert(token.clone()) {
            terms.push(format!("\"{token}\""));
            if terms.len() >= 24 {
                break;
            }
        }
    }
    (!terms.is_empty()).then(|| terms.join(" OR "))
}

/// Normalize a raw lexical score by the best score in the candidate set.
///
/// BM25 values are positive after the caller negates SQLite's `bm25()` output.
/// A top candidate therefore scores 1.0 and a candidate with no term overlap
/// stays 0.0.
pub fn normalize_lexical(score: f32, best: f32) -> f32 {
    if best <= 0.0 || !score.is_finite() {
        0.0
    } else {
        (score / best).clamp(0.0, 1.0)
    }
}

/// Blend lexical and vector relevance into one score in `0.0..=1.0`.
///
/// A lexical hit keeps a meaningful floor even when the local embedding cannot
/// see the relationship; a query with no lexical candidates still falls back to
/// the configured embedding's cosine score, which is what semantic backends
/// rely on.
pub fn blend(lexical: Option<f32>, vector_similarity: f32) -> f32 {
    let vector = if vector_similarity.is_finite() {
        vector_similarity.clamp(0.0, 1.0)
    } else {
        0.0
    };
    match lexical {
        Some(lexical) if lexical > 0.0 => {
            LEXICAL_WEIGHT * lexical.clamp(0.0, 1.0) + VECTOR_WEIGHT * vector
        }
        _ => vector,
    }
}

/// Importance boost used by both memory stores.
pub fn importance_boost(importance: f32) -> f32 {
    0.7 + 0.3 * importance.clamp(0.0, 1.0)
}

/// Small bounded boost for frequently useful memories. Recall must not make a
/// fact rank lower on every later retrieval.
pub fn usage_boost(access_count: u32) -> f32 {
    1.0 + access_count.min(20) as f32 * 0.01
}

/// BM25 over an in-memory document set, used by the retrieval benchmark.
///
/// SQLite computes BM25 for stored memories; the benchmark cannot depend on a
/// database, so it needs the same shape. Parameters are the standard `k1=1.2`
/// and `b=0.75`.
pub fn bm25_scores(documents: &[&str], query: &str) -> Vec<f32> {
    let query_terms = tokenize(query);
    let tokenized: Vec<Vec<String>> = documents.iter().map(|text| tokenize(text)).collect();
    let mut scores = vec![0.0f32; documents.len()];
    if query_terms.is_empty() || tokenized.is_empty() {
        return scores;
    }

    let total = tokenized.len() as f32;
    let average_length = tokenized.iter().map(|doc| doc.len() as f32).sum::<f32>() / total;
    let mut document_frequency = std::collections::HashMap::new();
    for doc in &tokenized {
        let unique: std::collections::HashSet<&String> = doc.iter().collect();
        for term in unique {
            *document_frequency.entry(term.as_str()).or_insert(0usize) += 1;
        }
    }

    let mut seen_query_terms = std::collections::HashSet::new();
    for term in &query_terms {
        if !seen_query_terms.insert(term.as_str()) {
            continue;
        }
        let frequency = *document_frequency.get(term.as_str()).unwrap_or(&0) as f32;
        if frequency == 0.0 {
            continue;
        }
        let idf = (1.0 + (total - frequency + 0.5) / (frequency + 0.5)).ln();
        for (index, doc) in tokenized.iter().enumerate() {
            let term_frequency = doc.iter().filter(|candidate| *candidate == term).count() as f32;
            if term_frequency == 0.0 {
                continue;
            }
            let length = doc.len() as f32;
            let denominator =
                term_frequency + 1.2 * (1.0 - 0.75 + 0.75 * length / average_length.max(1.0));
            scores[index] += idf * (term_frequency * 2.2) / denominator;
        }
    }
    scores
}

/// Cosine similarity with a zero vector guard, exposed for callers that already
/// have embeddings and do not need the store's full scoring path.
pub fn similarity(a: &[f32], b: &[f32]) -> f32 {
    cosine_similarity(a, b)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn stop_words_are_sorted_for_binary_search() {
        assert!(
            STOP_WORDS.windows(2).all(|pair| pair[0] < pair[1]),
            "STOP_WORDS must stay sorted because tokenization binary-searches it"
        );
    }

    #[test]
    fn tokenization_drops_stop_words_and_punctuation() {
        assert_eq!(
            tokenize("When does the release train leave?"),
            vec!["release", "train", "leave"]
        );
        assert_eq!(
            tokenize("on-call: 14:00 UTC"),
            vec!["call", "14", "00", "utc"]
        );
    }

    #[test]
    fn fts_query_quotes_terms_and_uses_or() {
        assert_eq!(
            fts_match_query("release train").as_deref(),
            Some("\"release\" OR \"train\"")
        );
        assert_eq!(fts_match_query("the what"), None);
        let query = fts_match_query("error: \"quoted\" AND (bad)");
        assert_eq!(query.as_deref(), Some("\"error\" OR \"quoted\" OR \"bad\""));
    }

    #[test]
    fn bm25_ranks_the_matching_document_first() {
        let docs = [
            "The release train departs every Thursday",
            "The office printer is on the second floor",
            "Customer backups are retained for thirty days",
        ];
        let scores = bm25_scores(&docs, "When does the release train leave?");
        assert!(scores[0] > scores[1]);
        assert!(scores[0] > scores[2]);
    }

    #[test]
    fn blend_keeps_a_lexical_floor_and_vector_fallback() {
        assert!((blend(Some(1.0), 0.0) - 0.6).abs() < 1e-6);
        assert!((blend(None, 0.5) - 0.5).abs() < 1e-6);
        assert!((blend(Some(1.0), 1.0) - 1.0).abs() < 1e-6);
        assert_eq!(blend(None, f32::NAN), 0.0);
    }
}
