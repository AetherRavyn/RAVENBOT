<script lang="ts">
  /**
   * A fenced code block: language chip, copy, and the artifact hand-off.
   *
   * This used to be a `marked` `<pre>` that `enhanceCodeBlocks` walked the DOM
   * to find, wrap in a header, and give a copy button — on every re-render,
   * for every block in the message. Here the header is part of the component,
   * so it exists the moment the block does, and the copy handler closes over
   * the text instead of doing a `closest(".md-code-wrapper code")` lookup that
   * breaks the moment the markup changes.
   */
  import { Check, Copy, Expand } from "@lucide/svelte";  import { t } from "$lib/i18n";
  import { qualifiesAsArtifact } from "$lib/artifact";
  import { hl, hlLanguage, type Token } from "$lib/highlight";

  interface Props {
    code: string;
    language: string;
    streaming?: boolean;
    onOpenArtifact?: (code: string, lang: string) => void;
  }

  let { code, language, streaming = false, onOpenArtifact }: Props = $props();

  let copied = $state(false);
  let copyTimer: ReturnType<typeof setTimeout> | null = null;

  const display = $derived(language || "text");
  const canOpen = $derived(Boolean(onOpenArtifact) && !streaming && qualifiesAsArtifact(code));

  // Highlighting is skipped while the block is still arriving: the result
  // changes on every token, and re-tokenising per keystroke is the most
  // expensive thing this component could do.
  //
  // It is also skipped until the block is near the viewport. A long office
  // transcript can hold dozens of code blocks; colouring the ones below the
  // fold on mount is work nobody sees before scrolling. The observer keeps a
  // 600px lead so a block is already coloured by the time it arrives.
  let host = $state<HTMLDivElement | null>(null);
  let nearViewport = $state(false);
  const canObserve = typeof IntersectionObserver !== "undefined";
  const shouldHighlight = $derived(
    !streaming && (!canObserve || nearViewport),
  );
  const tokens = $derived(
    shouldHighlight
      ? hl(code, hlLanguage(language))
      : [{ type: "text" as const, text: code }],
  );

  $effect(() => {
    if (nearViewport || !host || typeof IntersectionObserver === "undefined") return;
    const observer = new IntersectionObserver(
      (entries) => {
        if (entries.some((entry) => entry.isIntersecting)) {
          nearViewport = true;
          observer.disconnect();
        }
      },
      { rootMargin: "600px 0px" },
    );
    observer.observe(host);
    return () => observer.disconnect();
  });

  /**
   * Split the highlight stream into display lines.
   *
   * Splitting the *tokens* rather than re-highlighting each line keeps a
   * multi-line block comment or template string one continuous token, so a
   * colour never resets at a line boundary. The gutter number is generated by
   * CSS, not by a DOM node, which is what keeps it out of a copy selection.
   */
  function splitTokensIntoLines(input: Token[]): Token[][] {
    const lines: Token[][] = [[]];
    for (const token of input) {
      if (token.type === "newline") {
        lines.push([]);
        continue;
      }
      const parts = token.text.split("\n");
      parts.forEach((part, index) => {
        if (index > 0) lines.push([]);
        if (part) lines[lines.length - 1].push({ type: token.type, text: part });
      });
    }
    return lines;
  }

  const lines = $derived(splitTokensIntoLines(tokens));

  async function copy() {
    try {
      await navigator.clipboard.writeText(code);
      copied = true;
      if (copyTimer) clearTimeout(copyTimer);
      copyTimer = setTimeout(() => (copied = false), 2000);
    } catch {
      // Permission denied: leave the button at rest rather than showing a
      // checkmark for a copy that never happened.
    }
  }

  function open() {
    if (!onOpenArtifact || !canOpen) return;
    onOpenArtifact(code, language);
  }

  $effect(() => {
    return () => {
      if (copyTimer) clearTimeout(copyTimer);
    };
  });
</script>

<div class="md-code" bind:this={host}>
  <div class="md-code-header">
    <span class="md-code-lang">{display}</span>
    <div class="md-code-actions">
      {#if canOpen}
        <button type="button" class="md-code-btn" title={t("markdown.artifactTip")} onclick={open}>
          <Expand class="size-3" />
          <span>{t("markdown.artifact")}</span>
        </button>
      {/if}
      <button
        type="button"
        class="md-code-btn"
        title={t("markdown.copyTitle")}
        aria-label={copied ? t("markdown.copied") : t("markdown.copy")}
        onclick={copy}
      >
        {#if copied}
          <Check class="size-3 text-[var(--success-text)]" />
        {:else}
          <Copy class="size-3" />
        {/if}
        <span>{copied ? t("markdown.copied") : t("markdown.copy")}</span>
      </button>
    </div>
  </div>
  <pre class="md-code-pre"><code class="language-{display}">
{#each lines as line, li (li)}
<span class="md-code-line" data-line={li + 1}><span class="md-code-line__content">{#each line as tok, ti (ti)}{#if tok.type === "text"}{tok.text}{:else}<span class="tok-{tok.type}">{tok.text}</span>{/if}{/each}{#if streaming && li === lines.length - 1}<span class="md-code-cursor" aria-hidden="true"></span>{/if}</span></span>
{/each}
</code></pre>
</div>
